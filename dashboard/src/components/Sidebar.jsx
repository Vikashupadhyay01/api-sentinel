import React from 'react';
import { useApp } from '../contexts/AppContext';

const NAV_ITEMS = [
  { id: 'overview', icon: HomeIcon, label: 'Home' },
  { id: 'endpoints', icon: EndpointsIcon, label: 'Endpoints' },
  { id: 'alerts', icon: AlertsIcon, label: 'Alerts', badge: true },
  { id: 'blocked', icon: BlockedIcon, label: 'Blocked' },
  { id: 'users', icon: UsersIcon, label: 'Users' },
  { id: 'reports', icon: ReportsIcon, label: 'Reports' },
  { id: 'setup', icon: SetupIcon, label: 'Setup' },
];

