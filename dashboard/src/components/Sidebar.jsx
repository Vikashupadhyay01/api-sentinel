export function Sidebar({ collapsed }) {
  const { activeTab, setActiveTab, unreadCount } = useApp();

  return (
    <aside className={`sidebar ${collapsed ? '' : 'expanded'}`} role="navigation" aria-label="Main navigation">
      {/* Logo */}
      <div className="sidebar-logo" aria-hidden="true">
        <svg width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="white" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round">
          <path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10z"/>
        </svg>
      </div>

      {/* Navigation */}
      <nav className="sidebar-nav">
        {NAV_ITEMS.map(item => {
          const Icon = item.icon;
          const isActive = activeTab === item.id;
          const badgeCount = item.badge ? unreadCount : 0;
          return (
            <button
              key={item.id}
              className={`nav-item ${isActive ? 'active' : ''}`}
              onClick={() => setActiveTab(item.id)}
              aria-label={item.label}
              aria-current={isActive ? 'page' : undefined}
              title={collapsed ? item.label : undefined}
            >
              <span className="nav-icon"><Icon /></span>
              <span className="nav-label">{item.label}</span>
              {badgeCount > 0 && (
                <span className="nav-badge" aria-label={`${badgeCount} unread alerts`}>{badgeCount}</span>
              )}
            </button>
          );
        })}
      </nav>
    </aside>
  );
}
